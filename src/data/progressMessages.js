function messages(stage, prefix, start, category, texts, options = {}) {
  return texts.map((text, index) => {
    const number = start + index
    const key = `${prefix}${String(number).padStart(3, '0')}`
    return {
      id: `${stage === 'ELEMENTARY' ? 'elem' : stage === 'MIDDLE' ? 'middle' : 'high'}_${String(number).padStart(3, '0')}`,
      stage,
      category,
      text,
      growthTypes: options.growthTypes?.[key] ?? null,
      schools: options.schools?.[key] ?? null,
    }
  })
}

